#include "cybsp.h"
#include "cy_utils.h"
#include "dmx.h"
#include "seeGridRF.h"
#include "fixtures.h"
#include "rdm.h"


#ifdef DEBUG

typedef struct {
    uint32_t tx_count;
    uint32_t rx_count;
    uint32_t loop_count;
    uint8_t     nrf24_status;
} debug_t;

volatile debug_t debug = {0,0,0,0};
#endif

/**
 * Systick
 */
    #define TICKS_PER_SECOND    1000
    volatile uint32_t msTicks = 0;

/**
 * Memory
 */
    uint8_t universe[512];

    /* config packets sent after each DMX frame, or on their own without DMX */
    #define CONFIGS_PER_FRAME   4
    #define CONFIG_IDLE_MS      33
    
/**
 * Hardware Declarations
 */

    dmx_t dmx = {
        .usic_ch = CYBSP_DEBUG_UART_HW,
        .irqN = CYBSP_DEBUG_UART_RECEIVE_BUFFER_STANDARD_EVENT_IRQN,
        .buffer = universe
    };

    sgRF_radio_t radioA = {
        .usic = USIC1,
        .spiHardware = usic_1_ch_0_HW,
        .spiSelo = XMC_SPI_CH_SLAVE_SELECT_0,
        .irqN = IRQ3_IRQn,
        .irqPort = RF_IRQ_A_PORT,
        .irqPin = RF_IRQ_A_PIN,
        .cePort = RF_CE_A_PORT,
        .cePin = RF_CE_A_PIN,
        .mode = GATEWAY,
        .data = universe
    };

    sgRF_radio_t radioB = {
        .usic = USIC1,
        .spiHardware = usic_1_ch_0_HW,
        .spiSelo = XMC_SPI_CH_SLAVE_SELECT_1,
        .irqN = IRQ9_IRQn,
        .irqPort = RF_IRQ_B_PORT,
        .irqPin = RF_IRQ_B_PIN,
        .cePort = RF_CE_B_PORT,
        .cePin = RF_CE_B_PIN,
        .mode = GATEWAY,
        .data = universe
    };

    /* design.modus configures P4.8 as plain GPIO; route it to USIC1_CH0.SELO1 */
    static const XMC_GPIO_CONFIG_t RF_CSN_B_selo_config = {
        .mode = (XMC_GPIO_MODE_t)(XMC_GPIO_MODE_OUTPUT_PUSH_PULL | P4_8_AF_U1C0_SELO1),
        .output_level = XMC_GPIO_OUTPUT_LEVEL_HIGH,
    };


    void IRQ3_Handler (void) {
        sgRF_radioIrqHandler(&radioA);
    }

    void IRQ9_Handler (void) {
        sgRF_radioIrqHandler(&radioB);
    }

    void CYBSP_DEBUG_UART_RECEIVE_BUFFER_STANDARD_EVENT_HANDLER (void) {
        dmx_rxIrqHandler(&dmx);
    }

int main(void)
{
    cy_rslt_t result;

    /* Initialize the device and board peripherals */
    result = cybsp_init();
    if (result != CY_RSLT_SUCCESS)
    {
        CY_ASSERT(0);
    }

    XMC_GPIO_Init(RF_CSN_B_PORT, RF_CSN_B_PIN, &RF_CSN_B_selo_config);

    SysTick_Config(SystemCoreClock / TICKS_PER_SECOND);

    dmx_init(&dmx);
    sgRF_init(&radioA);
    sgRF_init(&radioB);
    /* radioA broadcasts DMX (+ config), radioB receives the fixture heartbeats */
    sgRF_enableStatusReceiver(&radioB);
    XMC_Delay(250);

    for (;;)
    {
        dmx_handle(&dmx);

        static uint32_t last_tx_ms;
        const bool frame = dmx_newFrame(&dmx);
        if ((frame || msTicks - last_tx_ms >= CONFIG_IDLE_MS) && sgRF_readyToBroadcast(&radioA)) {
            const sgRF_config_t* cfg = fixtures_nextConfig();
            if (frame || cfg != NULL) {
                sgRF_enableBroadcastTransmitter(&radioA);
                if (frame) sgRF_broadcastDmxFrame(&radioA, universe);
                /* config changes ride in the gap after the frame */
                for (uint8_t i = 0; i < CONFIGS_PER_FRAME && cfg != NULL; i++) {
                    sgRF_broadcastConfig(&radioA, cfg);
                    if (i + 1 < CONFIGS_PER_FRAME) cfg = fixtures_nextConfig();
                }
                sgRF_disableBroadcastTransmitter(&radioA);
                last_tx_ms = msTicks;
            }
            if (frame) dmx_clearFrame(&dmx);
        }

        sgRF_handle(&radioA);
        sgRF_handle(&radioB);
        sgRF_heartbeat_t hb;
        while (sgRF_readHeartbeat(&radioB, &hb)) {
            fixtures_heartbeat(&hb, msTicks);
        }

        const uint8_t* rdm_req;
        uint16_t rdm_len;
        bool rdm_disc;
        if (dmx_rdmRequest(&dmx, &rdm_req, &rdm_len, &rdm_disc)) {
            rdm_handle(&dmx, rdm_req, rdm_len, rdm_disc, msTicks);
            dmx_rdmDone(&dmx);
        }

        #ifdef DEBUG
        debug.loop_count++;
        #endif
    }
}

void SysTick_Handler(void) {
    msTicks++;
}

