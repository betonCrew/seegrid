#include "cybsp.h"
#include "cy_utils.h"
#include "dmx.h"
#include "seeGridRF.h"

#ifdef DEBUG

typedef struct {
    uint32_t tx_count;
    uint32_t rx_count;
    uint32_t loop_count;
    uint8_t     nrf24_status;
} debug_t;

volatile debug_t debug = {0,0,0,0};
#endif

/**
 * Systick
 */
    #define TICKS_PER_SECOND    1000
    volatile uint32_t msTicks = 0;

/**
 * Memory
 */
    uint8_t universe[512];
    
/**
 * Hardware Declarations
 */

    dmx_t dmx = {
        .usic_ch = CYBSP_DEBUG_UART_HW,
        .buffer = universe
    };

    sgRF_radio_t radioA = {
        .usic = USIC1,
        .spiHardware = usic_1_ch_0_HW,
        .irqN = IRQ3_IRQn,
        .irqPort = RF_IRQ_PORT,
        .irqPin = RF_IRQ_PIN,
        .cePort = RF_CE_PORT,
        .cePin = RF_CE_PIN,
        .mode = GATEWAY,
        .data = universe
    };

    void IRQ3_Handler (void) {
        sgRF_radioIrqHandler(&radioA);
    }

int main(void)
{
    cy_rslt_t result;

    /* Initialize the device and board peripherals */
    result = cybsp_init();
    if (result != CY_RSLT_SUCCESS)
    {
        CY_ASSERT(0);
    }

    SysTick_Config(SystemCoreClock / TICKS_PER_SECOND);

    dmx_handle(&dmx);
    sgRF_init(&radioA);
    XMC_Delay(250);

    for (;;)
    {
        dmx_handle(&dmx);

        if (dmx_newFrame(&dmx) && sgRF_readyToBroadcast(&radioA)) {
            sgRF_enableBroadcastTransmitter(&radioA);
            sgRF_broadcastDmxFrame(&radioA, universe);
            sgRF_disableBroadcastTransmitter(&radioA);
            dmx_clearFrame(&dmx);
        }

        sgRF_handle(&radioA);

        #ifdef DEBUG
        debug.loop_count++;
        #endif
    }
}

void SysTick_Handler(void) {
    msTicks++;
}

