/**
 * MAIN
 */
    int main(void)
    {

        /* Initialize the device and board peripherals */
        cy_rslt_t result;
        result = cybsp_init();
        if (result != CY_RSLT_SUCCESS)
        {
            CY_ASSERT(0);
        }
        SysTick_Config(SystemCoreClock / TICKS_PER_SECOND);
        led_init(&led);
        // battLvl_init(&batt);
        // boostCon_init(&boost);
        // sgRF_init(&radio);

        /* test sequence */
        led_enable(&led);
        for (int i=0; i<4; i++) {
            led_setColor(&led, *(led_color_t*)test_seq[i]);
            led_setWhite(&led, test_seq[i][3]);
            XMC_Delay(333);
        }
        led_setColorPreset(&led, COL_BLACK);
        led_setWhite(&led, 0x0000);

        saturday.index = 0;

        for (;;)
        {
            /* Decide about current cue */
            const uint32_t rtc_flags = XMC_RTC_GetEventStatus();
            if (rtc_flags & XMC_RTC_EVENT_ALARM) {
                nextCue(&saturday);
                XMC_RTC_ClearEvent(XMC_RTC_EVENT_ALARM);
            }

            /* Run Cue */
            const cue_t* current = saturday.data + saturday.index;
            ledFx_run(&led, current->fx, current->col);
        }
    }

    void SysTick_Handler(void) {
        msTicks++;
    }

